/**
 * 예제 선택 상자에 보이는 이름을 학생 말로 다듬는다(판 1.3.0 검수 R1-100).
 *
 * 예제 이름은 사이드카(examples/**.meta.yaml)와 코드가 만든 묶음 이름에서 오는데, 만드는 사람 말이 그대로 보였다:
 *  - "(사이트판" → "(이 사이트용": 교과서 코드에 줄을 더해 이 사이트에서 잘 돌게 고친 판. 학생에게는 "사이트판"이 무슨 판인지 알 수 없다.
 *  - "원본 파일" → "교과서 그대로": 고치지 않은 교과서 코드(일부러 틀린 결과가 나오는 것도 있다).
 *  - "계단" → "단계": 교안의 계단 번호는 "몇 단계"라는 뜻이다(계단은 층계로 읽힌다).
 * 선택 상자와 묶음 이름에만 쓴다. 예제 id·파일 이름·갤러리 카드·사이드카 원문은 그대로다(원문을 바꾸는 일은 콘텐츠 쪽 몫 — 통합이 정한다).
 * 바뀐 것이 없으면 같은 글을 그대로 돌려준다.
 */
export function studentExampleTitle(title: string): string {
  return title.replace(/\(사이트판/gu, '(이 사이트용').replace(/원본 파일/gu, '교과서 그대로').replace(/계단/gu, '단계');
}
