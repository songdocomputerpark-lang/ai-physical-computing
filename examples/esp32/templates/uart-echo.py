# 통신 템플릿 1: UART 에코 — 받은 줄을 그대로 돌려보내기
# 컴퓨터가 USB-UART 변환기로 보낸 한 줄을 보드가 그대로 다시 보내요. 선이 제대로 이어졌는지 확인하는 가장 기본 코드예요.
# @lesson 3-1-2
# @tags UART, 시리얼, 에코, 통신, 템플릿
# @part uart rx=17 tx=16
from machine import UART
from time import sleep

# UART2: 보드 TX(17) → 변환기 RX, 보드 RX(16) ← 변환기 TX. 두 선은 서로 엇갈리게 이어요(TX ↔ RX).
# timeout=200은 "한 줄이 다 올 때까지 0.2초까지 기다린다"는 뜻이에요. 안 오면 readline()이 None을 줘요.
uart = UART(2, baudrate=9600, tx=17, rx=16, timeout=200)

count = 0  # 지금까지 돌려보낸 줄 수

while True:
    line = uart.readline()  # 줄바꿈(\n)까지 한 줄. 아무것도 안 오면 None
    if line:
        text = line.decode().strip()  # bytes → 글자, 끝의 줄바꿈·공백을 떼요.
        count = count + 1
        print(count, "번째 줄 받음:", text)
        uart.write(text + "\n")  # 그대로 돌려보내요 — 끝에 줄바꿈 한 개(메시지 규칙)
    sleep(0.05)

# ── 실습 방법 ──
# 1. [실행]을 눌러요. 보드가 UART2를 열고 글자가 오기를 기다려요(아직 아무 일도 없는 것이 정상이에요).
# 2. 보드 아래 "USB-UART 변환기 조작" 칸의 [보낼 글자]에 hello를 적고 [보내기]를 눌러요.
# 3. 콘솔에 "1 번째 줄 받음: hello"가 나오고, 같은 칸의 [보드가 보낸 글자]에 hello가 되돌아오면 성공이에요.
# 4. 속도를 115200으로 바꿔 다시 보내면 글자가 깨져요 — 보내는 쪽과 받는 쪽 속도가 같아야 해요.
# ── 바꿔볼 것 3가지 ──
# 1. uart.write(text + "\n")을 uart.write(text.upper() + "\n")으로 바꿔 대문자로 돌려보내 봐요.
# 2. timeout=200을 timeout=0으로 바꾸고 긴 글을 보내 봐요. 줄이 중간에서 잘려 오는 일이 생겨요.
# 3. if line: 아래에 if text == "a": 를 넣어 a를 받았을 때만 무언가를 하게 바꿔 봐요(3-1-2의 레이저 켜기처럼).
# ── 왜 이런 결과가 나올까 ──
# UART는 선 한 가닥으로 바이트를 하나씩 보내요. 받는 쪽은 받은 바이트를 버퍼에 쌓아 두었다가 우리가 읽을 때 꺼내 줘요.
# 그래서 두 글자를 빠르게 보내면 한 번에 "ab"로 읽히기도 해요. 줄바꿈(\n)을 끝 표시로 쓰면 어디까지가 한 메시지인지 알 수 있어요.
# 한 번에 보내는 메시지는 20바이트 안쪽으로 짧게 만들어요. 블루투스로 같은 글을 보낼 때 한 번에 갈 수 있는 크기가 20바이트라서,
# 같은 규칙으로 맞춰 두면 UART로 만든 코드를 블루투스·MQTT로 그대로 옮길 수 있어요.
