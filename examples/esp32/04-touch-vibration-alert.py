# 진동 알림: 터치하면 진동 모터가 두 번 떨려요
# 터치 센서(GPIO17)를 누르는 순간 진동 모터(GPIO19)가 "징-징" 두 번 떨려 알려 줘요. 휴대폰의 진동 알림과 같은 원리예요.
# @lesson 2-2-1
# @tags 진동 모터, 터치 센서, 출력, 입력
# @part touch-digital 17
# @part vibration-motor 19
# 진동 모터의 19번 핀은 원고에 핀 번호가 없어 사이트가 정한 핀이에요(실물 키트에서 확인 전). 다른 핀에 꽂았다면 19를 그 번호로 바꿔요.
# 이때 위의 "# @part vibration-motor 19" 줄도 같은 번호로 바꿔야 화면 속 배선도와 진동 모터가 따라와요.
from machine import Pin
from time import sleep

buzz_time = 0.3  # @slider 0.1 1 0.1 한 번 떨리는 시간(초)

touch = Pin(17, Pin.IN)  # 터치 센서: 누르고 있는 동안 1, 떼면 0
motor = Pin(19, Pin.OUT)  # 진동 모터: 1(HIGH)을 내보내면 떨려요


def alert():  # 진동 모터를 두 번 떨게 하는 함수
    for count in range(2):  # 두 번 되풀이해요.
        motor.on()  # 떨기 시작
        sleep(buzz_time)  # buzz_time초 동안 떨어요.
        motor.off()  # 멈춤
        sleep(0.2)  # 두 번 사이를 조금 띄워요.


last = 0  # 바로 전에 읽은 터치 값
while True:
    now = touch.value()  # 지금 터치 값(0 또는 1)
    if now == 1 and last == 0:  # 0에서 1로 바뀐 순간(방금 누름)에만
        print("알림!")
        alert()
    last = now  # 다음 비교를 위해 지금 값을 기억해요.
    sleep(0.05)  # 0.05초마다 다시 확인해요.

# ── 실습 방법 ──
# 1. [실행]을 눌러요.
# 2. 보드 아래 터치 센서를 마우스나 손가락으로 한 번 눌러요(Tab 키로 옮겨 Space를 눌러도 돼요).
# 3. 콘솔에 "알림!"이 나오고 진동 모터가 두 번 떨리는지 봐요.
# ── 바꿔볼 것 3가지 ──
# 1. 조절 막대로 buzz_time을 0.1과 1로 바꿔 가며 눌러 봐요. 어느 쪽이 알림으로 알아차리기 쉬운가요?
# 2. range(2)를 range(3)으로 바꿔 세 번 떨게 해 봐요.
# 3. 누르고 있는 동안에는 계속 떨고, 떼면 멈추게 바꿔 봐요. (힌트: if now == 1이면 motor.on(), 아니면 motor.off())
# ── 왜 이런 결과가 나올까 ──
# 진동 모터는 1(HIGH)을 받는 동안 한쪽으로 치우친 추를 돌려 떨려요. on()과 off() 사이를 얼마나 두느냐가 떨리는 시간이에요.
# last와 now를 비교해 0에서 1로 바뀐 순간에만 alert()를 불러서, 손가락을 계속 대고 있어도 알림은 한 번만 울려요.
# alert()가 떠는 동안(약 1초)에는 터치 값을 읽지 않아요. 그동안 눌렀다 뗀 것은 놓칠 수 있어요.
