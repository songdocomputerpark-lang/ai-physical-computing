# 3. 결과 글자를 "가"로 골라 실행해요. 글자 하나인데 바이트는 몇 개가 나오나요?
# ── 왜 이런 결과가 나올까 ──
# 컴퓨터는 글자를 번호(아스키코드)로 저장해요. 그래서 문자 '1'은 49, 쉼표는 44, 줄바꿈은 10이라는 바이트가 돼요.
# 받는 쪽은 바이트를 글자로 되돌린 뒤, 보내는 쪽과 미리 약속한 대로 줄바꿈에서 자르고 쉼표에서 나눠요.
# 나눈 조각은 아직 글자라서 int()로 정수로 바꿔야 x < 100 같은 크기 비교를 할 수 있어요.
# 한글은 아스키코드에 없어서 UTF-8 규칙으로 한 글자가 3바이트가 돼요. 그래서 통신 메시지는 영어와 숫자로 짧게 만들어요.
