# 3-1-1 체험: 문자열 ↔ bytes 변환기
# 컴퓨터가 보낼 글자가 바이트(0~255 숫자)로 바뀌고, 보드가 받은 바이트를 다시 글자와 정수로 되돌리는 과정을 한 단계씩 보여 줘요.
# @lesson 3-1-1
# @tags 통신, 바이트, 아스키코드, 문자열, 프로토콜, split
# 카메라와 보드가 없어도 돼요. 오른쪽 아래 조절 패널에서 값을 바꾼 뒤 다시 [실행]해 봐요.

finger_x = 120  # @slider 0 640 10 검지 끝의 x 좌표(픽셀)
finger_y = 250  # @slider 0 480 10 검지 끝의 y 좌표(픽셀)
result = "c"  # 보낼 결과 글자 @select a b c 1 가

# ① 글자 하나: 문자 '1'과 숫자 1은 서로 다른 바이트예요.
letter = "1".encode("utf-8")  # 문자 '1' → 바이트(인코딩)
number = bytes([1])  # 숫자 1 → 바이트 하나
print("① 글자 하나")
print("  문자 '1' → 바이트", list(letter), f"(16진수 0x{letter[0]:02X})")
print("  숫자 1   → 바이트", list(number), f"(16진수 0x{number[0]:02X})")
print("  결과 글자", repr(result), "→ 바이트", list(result.encode("utf-8")))

# ② 보내는 쪽(컴퓨터): 약속한 모양(x,y + 줄바꿈)의 글자 한 줄을 만들고 바이트로 바꿔요.
message = f"{finger_x},{finger_y}\n"  # 쉼표로 나누고, 끝에 줄바꿈 문자(\n)를 붙여요.
data = message.encode("utf-8")  # 문자열 → bytes
print("② 보내는 쪽(컴퓨터)")
print("  보낼 글자 한 줄:", repr(message))
pairs = [f"{char!r}→{value}" for char, value in zip(message, data)]  # 글자마다 바이트 값
print("  한 글자씩:", "  ".join(pairs))
print(f"  모두 {len(data)}바이트:", list(data))

# ③ 받는 쪽(보드): 바이트를 글자로 되돌리고, 줄바꿈을 떼고, 쉼표로 나눠 정수로 바꿔요.
text = data.decode("utf-8").strip()  # bytes → 문자열(디코딩), 앞뒤의 줄바꿈·빈칸 떼기
values = text.split(",")  # "120,250" → ["120", "250"]
x = int(values[0])  # "120" → 120
y = int(values[1])  # "250" → 250
print("③ 받는 쪽(보드)")
print("  글자로 되돌리고 줄바꿈 떼기:", repr(text))
print("  쉼표로 나누기:", values)
print("  정수로 바꾸기: x =", x, "/ y =", y)

# ④ 받은 값으로 할 일을 정해요(3-1-3 보드 코드와 같은 규칙).
if x < 100:
    print("④ 할 일: 빨간 LED를 켜요")
elif y < 100:
    print("④ 할 일: 초록 LED를 켜요")
else:
    print("④ 할 일: 파란 LED를 켜요")

